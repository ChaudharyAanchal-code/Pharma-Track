-- PharmaTrack: Smart Pharmacy Inventory & Expiry Management
-- Oracle Database 12c or later.

CREATE TABLE pharma_supplier (
    supplier_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_name VARCHAR2(150) NOT NULL,
    phone         VARCHAR2(30),
    email         VARCHAR2(150)
);

CREATE TABLE pharma_medicine (
    medicine_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicine_name VARCHAR2(150) NOT NULL,
    generic_name  VARCHAR2(150),
    category      VARCHAR2(80),
    unit          VARCHAR2(30) DEFAULT 'unit' NOT NULL,
    reorder_level NUMBER(10, 2) DEFAULT 0 NOT NULL,
    CONSTRAINT pharma_medicine_reorder_ck CHECK (reorder_level >= 0)
);

CREATE TABLE pharma_batch (
    batch_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicine_id    NUMBER NOT NULL REFERENCES pharma_medicine (medicine_id),
    supplier_id    NUMBER REFERENCES pharma_supplier (supplier_id),
    batch_number   VARCHAR2(80) NOT NULL UNIQUE,
    received_date  DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    expiry_date    DATE NOT NULL,
    quantity_on_hand NUMBER(10, 2) NOT NULL,
    unit_cost      NUMBER(10, 2) DEFAULT 0 NOT NULL,
    CONSTRAINT pharma_batch_qty_ck CHECK (quantity_on_hand >= 0),
    CONSTRAINT pharma_batch_cost_ck CHECK (unit_cost >= 0)
);

CREATE INDEX pharma_batch_fefo_ix
    ON pharma_batch (medicine_id, expiry_date, batch_id);

CREATE TABLE pharma_stock_transaction (
    transaction_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id       NUMBER NOT NULL REFERENCES pharma_batch (batch_id),
    transaction_type VARCHAR2(10) NOT NULL,
    quantity       NUMBER(10, 2) NOT NULL,
    reference      VARCHAR2(100),
    transaction_date TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pharma_stock_txn_type_ck
        CHECK (transaction_type IN ('RECEIVE', 'DISPENSE', 'ADJUST')),
    CONSTRAINT pharma_stock_txn_qty_ck CHECK (quantity > 0)
);

CREATE TABLE pharma_inventory_alert (
    alert_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicine_id   NUMBER NOT NULL REFERENCES pharma_medicine (medicine_id),
    batch_id      NUMBER REFERENCES pharma_batch (batch_id),
    alert_type    VARCHAR2(20) NOT NULL,
    alert_message VARCHAR2(500) NOT NULL,
    status        VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
    created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    resolved_at   TIMESTAMP,
    CONSTRAINT pharma_alert_type_ck
        CHECK (alert_type IN ('EXPIRED', 'EXPIRES_SOON', 'LOW_STOCK')),
    CONSTRAINT pharma_alert_status_ck CHECK (status IN ('ACTIVE', 'RESOLVED'))
);

CREATE INDEX pharma_alert_status_ix
    ON pharma_inventory_alert (status, alert_type);

CREATE OR REPLACE PACKAGE pharmatrack_pkg AS
    PROCEDURE receive_stock (
        p_medicine_id IN  NUMBER,
        p_batch_number IN VARCHAR2,
        p_expiry_date IN  DATE,
        p_quantity IN NUMBER,
        p_unit_cost IN NUMBER DEFAULT 0,
        p_supplier_id IN NUMBER DEFAULT NULL,
        p_batch_id OUT NUMBER
    );

    PROCEDURE dispense_stock (
        p_medicine_id IN NUMBER,
        p_quantity IN NUMBER,
        p_reference IN VARCHAR2 DEFAULT NULL
    );

    PROCEDURE refresh_alerts (
        p_expiry_window_days IN NUMBER DEFAULT 90
    );
END pharmatrack_pkg;
/

CREATE OR REPLACE PACKAGE BODY pharmatrack_pkg AS
    PROCEDURE receive_stock (
        p_medicine_id IN  NUMBER,
        p_batch_number IN VARCHAR2,
        p_expiry_date IN  DATE,
        p_quantity IN NUMBER,
        p_unit_cost IN NUMBER,
        p_supplier_id IN NUMBER,
        p_batch_id OUT NUMBER
    ) IS
    BEGIN
        SAVEPOINT pharmatrack_receive_sp;

        IF p_quantity IS NULL OR p_quantity <= 0 THEN
            RAISE_APPLICATION_ERROR(-20001, 'Received quantity must be greater than zero.');
        END IF;

        IF p_unit_cost IS NULL OR p_unit_cost < 0 THEN
            RAISE_APPLICATION_ERROR(-20002, 'Unit cost cannot be negative.');
        END IF;

        IF p_expiry_date IS NULL OR p_expiry_date < TRUNC(SYSDATE) THEN
            RAISE_APPLICATION_ERROR(-20003, 'Expiry date cannot be in the past.');
        END IF;

        INSERT INTO pharma_batch (
            medicine_id, supplier_id, batch_number, expiry_date,
            quantity_on_hand, unit_cost
        ) VALUES (
            p_medicine_id, p_supplier_id, p_batch_number, TRUNC(p_expiry_date),
            p_quantity, p_unit_cost
        )
        RETURNING batch_id INTO p_batch_id;

        INSERT INTO pharma_stock_transaction (
            batch_id, transaction_type, quantity, reference
        ) VALUES (
            p_batch_id, 'RECEIVE', p_quantity, 'Stock received'
        );
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK TO pharmatrack_receive_sp;
            RAISE;
    END receive_stock;

    PROCEDURE dispense_stock (
        p_medicine_id IN NUMBER,
        p_quantity IN NUMBER,
        p_reference IN VARCHAR2
    ) IS
        CURSOR c_batches IS
            SELECT batch_id, quantity_on_hand
            FROM pharma_batch
            WHERE medicine_id = p_medicine_id
              AND expiry_date >= TRUNC(SYSDATE)
              AND quantity_on_hand > 0
            ORDER BY expiry_date, batch_id
            FOR UPDATE;

        v_remaining NUMBER(10, 2) := p_quantity;
        v_take      NUMBER(10, 2);
        v_batch_id  NUMBER;
        v_available NUMBER(10, 2);
    BEGIN
        SAVEPOINT pharmatrack_dispense_sp;

        IF p_quantity IS NULL OR p_quantity <= 0 THEN
            RAISE_APPLICATION_ERROR(-20004, 'Dispense quantity must be greater than zero.');
        END IF;

        OPEN c_batches;
        LOOP
            FETCH c_batches INTO v_batch_id, v_available;
            EXIT WHEN c_batches%NOTFOUND OR v_remaining = 0;

            v_take := LEAST(v_available, v_remaining);

            UPDATE pharma_batch
            SET quantity_on_hand = quantity_on_hand - v_take
            WHERE CURRENT OF c_batches;

            INSERT INTO pharma_stock_transaction (
                batch_id, transaction_type, quantity, reference
            ) VALUES (
                v_batch_id, 'DISPENSE', v_take, p_reference
            );

            v_remaining := v_remaining - v_take;
        END LOOP;
        CLOSE c_batches;

        IF v_remaining > 0 THEN
            RAISE_APPLICATION_ERROR(
                -20005,
                'Insufficient unexpired stock. Unfilled quantity: ' || v_remaining
            );
        END IF;
    EXCEPTION
        WHEN OTHERS THEN
            IF c_batches%ISOPEN THEN
                CLOSE c_batches;
            END IF;
            ROLLBACK TO pharmatrack_dispense_sp;
            RAISE;
    END dispense_stock;

    PROCEDURE refresh_alerts (
        p_expiry_window_days IN NUMBER
    ) IS
    BEGIN
        IF p_expiry_window_days IS NULL OR p_expiry_window_days < 0 THEN
            RAISE_APPLICATION_ERROR(-20006, 'Expiry window cannot be negative.');
        END IF;

        MERGE INTO pharma_inventory_alert a
        USING (
            SELECT b.medicine_id,
                   b.batch_id,
                   CASE
                       WHEN b.expiry_date < TRUNC(SYSDATE) THEN 'EXPIRED'
                       ELSE 'EXPIRES_SOON'
                   END AS alert_type,
                   'Batch ' || b.batch_number || ' expires on '
                       || TO_CHAR(b.expiry_date, 'YYYY-MM-DD') AS alert_message
            FROM pharma_batch b
            WHERE b.quantity_on_hand > 0
              AND b.expiry_date <= TRUNC(SYSDATE) + p_expiry_window_days

            UNION ALL

            SELECT m.medicine_id,
                   CAST(NULL AS NUMBER) AS batch_id,
                   'LOW_STOCK' AS alert_type,
                   'Stock is at or below reorder level for '
                       || m.medicine_name AS alert_message
            FROM pharma_medicine m
            WHERE (
                SELECT NVL(SUM(b.quantity_on_hand), 0)
                FROM pharma_batch b
                WHERE b.medicine_id = m.medicine_id
                  AND b.expiry_date >= TRUNC(SYSDATE)
            ) <= m.reorder_level
        ) s
        ON (
            a.medicine_id = s.medicine_id
            AND NVL(a.batch_id, 0) = NVL(s.batch_id, 0)
            AND a.alert_type = s.alert_type
        )
        WHEN MATCHED THEN
            UPDATE SET a.alert_message = s.alert_message,
                       a.status = 'ACTIVE',
                       a.resolved_at = NULL
        WHEN NOT MATCHED THEN
            INSERT (
                medicine_id, batch_id, alert_type, alert_message, status
            ) VALUES (
                s.medicine_id, s.batch_id, s.alert_type, s.alert_message, 'ACTIVE'
            );

        UPDATE pharma_inventory_alert a
        SET a.status = 'RESOLVED',
            a.resolved_at = SYSTIMESTAMP
        WHERE a.status = 'ACTIVE'
          AND (
              (
                  a.alert_type IN ('EXPIRED', 'EXPIRES_SOON')
                  AND NOT EXISTS (
                      SELECT 1
                      FROM pharma_batch b
                      WHERE b.batch_id = a.batch_id
                        AND b.quantity_on_hand > 0
                        AND b.expiry_date <= TRUNC(SYSDATE) + p_expiry_window_days
                        AND (
                            (a.alert_type = 'EXPIRED'
                             AND b.expiry_date < TRUNC(SYSDATE))
                            OR
                            (a.alert_type = 'EXPIRES_SOON'
                             AND b.expiry_date >= TRUNC(SYSDATE))
                        )
                  )
              )
              OR
              (
                  a.alert_type = 'LOW_STOCK'
                  AND (
                      SELECT NVL(SUM(b.quantity_on_hand), 0)
                      FROM pharma_batch b
                      WHERE b.medicine_id = a.medicine_id
                        AND b.expiry_date >= TRUNC(SYSDATE)
                  ) > (
                      SELECT m.reorder_level
                      FROM pharma_medicine m
                      WHERE m.medicine_id = a.medicine_id
                  )
              )
          );
    END refresh_alerts;
END pharmatrack_pkg;
